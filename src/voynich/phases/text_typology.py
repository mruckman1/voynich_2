@dataclass
class MarkovGenerationTest:
    markov_order: int
    n_synthetic_texts: int
    voynich_stats: Dict[str, float]
    synthetic_stats: Dict[str, Dict[str, float]]  # metric -> {mean, std}
    n_metrics_within_2sigma: int
