@dataclass
class TypologyClassification:
    voynich_features: Dict[str, float]
    glossolalia_indicators: Dict[str, bool]
    constructed_lang_indicators: Dict[str, bool]
    natural_lang_indicators: Dict[str, bool]
    encoded_natural_indicators: Dict[str, bool]
    most_likely_type: str
    confidence: float


