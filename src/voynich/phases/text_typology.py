"""
Phase 9.5 — Text Typology Classification
==========================================

Rationale
---------
Every phase assumed the text encodes natural language.  The structural evidence
supports this but consistent decoding failure could mean the text has
language-LIKE properties generated by a different process.  This step tests
three alternatives without assuming the natural-language-cipher model.

Sub-analyses
------------
9.5a  Markov generation test (can a char Markov reproduce Voynich stats?)
9.5b  Glossolalia / constructed language classification
9.5c  Information density test (conditional entropy curves)
Null  Classify shuffled Voynich texts
"""

