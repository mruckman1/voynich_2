def run_text_typology() -> Dict:
    """
    Phase 9.5: Classify the Voynich text by typology — natural language,
    cipher, constructed language, or glossolalia.
    """
    print("Phase 9.5: Text Typology Classification")
    print("=" * 60)

    # --- Load data ---
    corpus = load_corpus(verbose=False)
    ref_corpus = load_reference_corpus(verbose=False)
    voynich_tokens = corpus.get_tokens(language='A')
    voynich_text = corpus.get_text(language='A')
    print(f"  Voynich Language A: {len(voynich_tokens):,} tokens, "
          f"{len(voynich_text):,} characters")

    # ===================================================================
    # 9.5a: Markov generation test
    # ===================================================================
    print("\n  9.5a: Markov generation test ...")
    markov_tests: List[MarkovGenerationTest] = []
    best_order = 1
    best_match = 0

    for order in (1, 2, 3):
        print(f"    Order {order} ...")
        mt = _run_markov_test(voynich_text, voynich_tokens, order, n_trials=30)
        markov_tests.append(mt)
        print(f"      Metrics within 2 sigma: {mt.n_metrics_within_2sigma}/{mt.n_metrics_total}")
        print(f"      Markov sufficient: {mt.markov_sufficient}")
        if mt.n_metrics_within_2sigma > best_match:
            best_match = mt.n_metrics_within_2sigma
            best_order = order

    print(f"    Best Markov order: {best_order} "
          f"({best_match}/{markov_tests[0].n_metrics_total} metrics)")

    # ===================================================================
    # 9.5b: Text type classification
    # ===================================================================
    print("\n  9.5b: Text type classification ...")
    v_features = _compute_text_stats(voynich_text, voynich_tokens)
    classification = _classify_text(v_features)

    print(f"    H2/H1 ratio: {v_features['h2_h1_ratio']:.3f}")
    print(f"    TTR: {v_features['ttr']:.4f}")
    print(f"    Zipf R²: {v_features['zipf_r_squared']:.4f}")
    print(f"    Classification: {classification.most_likely_type} "
          f"(confidence={classification.confidence:.2f})")
    print(f"    Glossolalia indicators: {classification.glossolalia_indicators}")
    print(f"    Constructed indicators: {classification.constructed_lang_indicators}")
    print(f"    Natural indicators: {classification.natural_lang_indicators}")
    print(f"    Encoded natural indicators: {classification.encoded_natural_indicators}")

    # ===================================================================
    # 9.5c: Information density / entropy curves
    # ===================================================================
    print("\n  9.5c: Information density (entropy curves) ...")
    max_order = 6  # Keep manageable for computation time

    v_curve = entropy_curve(voynich_text, max_order=max_order)
    print(f"    Voynich entropy curve: "
          + "  ".join(f"H{k}={v:.3f}" for k, v in sorted(v_curve.items())))

    ref_curves: Dict[str, Dict[int, float]] = {}
    for lang in ('latin', 'occitan', 'italian', 'german'):
        try:
            ref_text = ref_corpus.get_combined_text(lang)
            if len(ref_text) < 200:
                continue
            # Subsample to Voynich size for fair comparison
            ref_text = ref_text[:len(voynich_text)]
            rc = entropy_curve(ref_text, max_order=max_order)
            ref_curves[lang] = rc
            print(f"    {lang}: "
                  + "  ".join(f"H{k}={v:.3f}" for k, v in sorted(rc.items())))
        except Exception as e:
            print(f"    {lang}: failed — {e}")

    # Decay rates and floors
    v_decay = _entropy_decay_rate(v_curve)
    v_floor = v_curve.get(max_order, 0.0)
    ref_decays = {lang: _entropy_decay_rate(c) for lang, c in ref_curves.items()}
    ref_floors = {lang: c.get(max_order, 0.0) for lang, c in ref_curves.items()}

    print(f"    Voynich decay rate: {v_decay:.4f}  floor: {v_floor:.3f}")
    for lang in ref_decays:
        print(f"    {lang} decay rate: {ref_decays[lang]:.4f}  floor: {ref_floors[lang]:.3f}")

    # Find closest curve via DTW
    closest_lang = 'none'
    closest_dist = float('inf')
    v_seq = [v_curve[k] for k in sorted(v_curve.keys())]
    for lang, rc in ref_curves.items():
        r_seq = [rc[k] for k in sorted(rc.keys())]
        dist = dtw_distance(v_seq, r_seq)
        if dist < closest_dist:
            closest_dist = dist
            closest_lang = lang
    print(f"    Closest entropy curve: {closest_lang} (DTW={closest_dist:.4f})")

    info_density = InformationDensityTest(
        voynich_curve={int(k): v for k, v in v_curve.items()},
        reference_curves={lang: {int(k): v for k, v in c.items()}
                          for lang, c in ref_curves.items()},
        voynich_decay_rate=v_decay,
        reference_decay_rates=ref_decays,
        voynich_floor=v_floor,
        reference_floors=ref_floors,
        closest_curve_language=closest_lang,
        curve_distance=closest_dist,
    )

    # ===================================================================
    # Null test: classify shuffled Voynich
    # ===================================================================
    print("\n  Null test: shuffled Voynich classification ...")
    rng = random.Random(42)
    shuffled_tokens = voynich_tokens.copy()
    rng.shuffle(shuffled_tokens)
    shuffled_text = ' '.join(shuffled_tokens)
    shuffled_features = _compute_text_stats(shuffled_text, shuffled_tokens)
    shuffled_class = _classify_text(shuffled_features)
    print(f"    Word-shuffled classification: {shuffled_class.most_likely_type} "
          f"(confidence={shuffled_class.confidence:.2f})")

    # ===================================================================
    # Gate
    # ===================================================================
    gate_markov = best_match >= 5  # Markov reproduces >= 5/6 metrics
    gate_classification = classification.confidence >= 0.7
    gate_passed = gate_markov or gate_classification

    if gate_markov and classification.most_likely_type in ('glossolalia', 'constructed'):
        verdict = 'structure_is_low_order_not_linguistic'
    elif gate_markov and classification.most_likely_type in ('natural', 'encoded_natural'):
        verdict = 'markov_matches_but_classification_says_natural'
    elif gate_classification:
        verdict = f'classified_as_{classification.most_likely_type}'
    elif not gate_markov and not gate_classification:
        verdict = 'ambiguous_typology'
    else:
        verdict = 'inconclusive'

    print(f"\n  Gate: markov={gate_markov}  "
          f"classification={gate_classification}  passed={gate_passed}")
    print(f"  Verdict: {verdict}")

    # ===================================================================
    # Save
    # ===================================================================
    result = TextTypologyResult(
        markov_tests=[_convert(asdict(mt)) for mt in markov_tests],
        best_markov_order=best_order,
        best_markov_match=best_match,
        classification=_convert(asdict(classification)),
        entropy_curves=_convert(asdict(info_density)),
        null_shuffled_classification=shuffled_class.most_likely_type,
        gate_markov=gate_markov,
        gate_classification=gate_classification,
        gate_passed=gate_passed,
        verdict=verdict,
    )

    out = _convert(asdict(result))
    with open(_results_dir() / 'text_typology.json', 'w') as f:
        json.dump(out, f, indent=2)

    print(f"\n  Results saved to results/text_typology.json")
    return out
