def _convert(obj: Any) -> Any:
    """Convert dataclass/numpy types to JSON-serializable form."""
    if hasattr(obj, '__dataclass_fields__'):
        return {k: _convert(v) for k, v in asdict(obj).items()}
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, (np.floating,)):
        return float(obj)
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    if isinstance(obj, dict):
        return {str(k): _convert(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_convert(item) for item in obj]
    if isinstance(obj, (bool, int, float, str, type(None))):
        return obj
    return str(obj)


def _compute_text_stats(text: str, tokens: List[str]) -> Dict[str, float]:
    """Compute the 6 key metrics for any text."""
    h1 = first_order_entropy(text)
    h2 = conditional_entropy(text, order=1)
    h3 = conditional_entropy(text, order=2)
    za = zipf_analysis(tokens)
    wld = word_length_distribution(tokens)
    ttr_vals = type_token_ratio_at_n(tokens, n_values=[len(tokens)])
    ttr = ttr_vals.get(len(tokens), len(set(tokens)) / len(tokens) if tokens else 0.0)

    # Bigram entropy
    mat, alph = bigram_transition_matrix(text)
    flat = mat.flatten()
    flat = flat[flat > 0]
    flat = flat / flat.sum() if flat.sum() > 0 else flat
    bigram_ent = -float(np.sum(flat * np.log2(flat + 1e-15))) if len(flat) > 0 else 0.0

    return {
        'h1': h1,
        'h2': h2,
        'h3': h3,
        'h2_h1_ratio': h2 / h1 if h1 > 0 else 0.0,
        'zipf_exponent': za['zipf_exponent'],
        'zipf_r_squared': za['r_squared'],
        'word_length_mean': wld.get('mean', 0.0),
        'ttr': ttr,
        'bigram_entropy': bigram_ent,
    }


def _generate_markov_text(
    source_text: str, n_chars: int, order: int = 2, seed: int = 42,
) -> str:
    """Generate synthetic text from a character-level Markov model."""
    # Build transition tables directly from text
    chars = list(source_text)
    if len(chars) <= order:
        return source_text

    transitions: Dict[tuple, List[str]] = {}
    for i in range(len(chars) - order):
        ctx = tuple(chars[i:i + order])
        nxt = chars[i + order]
        transitions.setdefault(ctx, []).append(nxt)

    rng = random.Random(seed)
    # Start from a random context
    start = rng.randint(0, len(chars) - order - 1)
    ctx = tuple(chars[start:start + order])
    result = list(ctx)

    for _ in range(n_chars - order):
        candidates = transitions.get(ctx)
        if not candidates:
            # Fall back to random context
            start = rng.randint(0, len(chars) - order - 1)
            ctx = tuple(chars[start:start + order])
            result.append(ctx[-1])
            continue
        ch = rng.choice(candidates)
        result.append(ch)
        ctx = (*ctx[1:], ch)

    return ''.join(result)


def _run_markov_test(
    voynich_text: str, voynich_tokens: List[str],
    markov_order: int, n_trials: int = 30,
) -> MarkovGenerationTest:
    """Generate Markov text and compare stats to Voynich."""
    v_stats = _compute_text_stats(voynich_text, voynich_tokens)
    n_chars = len(voynich_text)

    # Metrics to compare (excluding h1 which is trivially matched)
    compare_metrics = ['h2', 'h3', 'zipf_exponent', 'word_length_mean', 'ttr', 'bigram_entropy']

    synth_stats_all: Dict[str, List[float]] = {m: [] for m in compare_metrics}

    for trial in range(n_trials):
        synth_text = _generate_markov_text(
            voynich_text, n_chars, order=markov_order, seed=42 + trial,
        )
        synth_tokens = synth_text.split()
        if len(synth_tokens) < 50:
            continue
        ss = _compute_text_stats(synth_text, synth_tokens)
        for m in compare_metrics:
            synth_stats_all[m].append(ss[m])

    # Compare: how many metrics are within 2 sigma?
    synth_summary: Dict[str, Dict[str, float]] = {}
    n_within = 0
    for m in compare_metrics:
        vals = synth_stats_all[m]
        if not vals:
            synth_summary[m] = {'mean': 0.0, 'std': 0.0}
            continue
        mean = float(np.mean(vals))
        std = float(np.std(vals))
        synth_summary[m] = {'mean': mean, 'std': std}
        if std > 0 and abs(v_stats[m] - mean) < 2 * std:
            n_within += 1
        elif std == 0 and abs(v_stats[m] - mean) < 0.01:
            n_within += 1

    return MarkovGenerationTest(
        markov_order=markov_order,
        n_synthetic_texts=n_trials,
        voynich_stats=v_stats,
        synthetic_stats=synth_summary,
        n_metrics_within_2sigma=n_within,
        n_metrics_total=len(compare_metrics),
        markov_sufficient=n_within >= 5,
    )


def _classify_text(features: Dict[str, float]) -> TypologyClassification:
    """Rule-based text type classification from statistical features."""
    h2_h1 = features.get('h2_h1_ratio', 0.0)
    ttr = features.get('ttr', 0.0)
    h3 = features.get('h3', 0.0)
    zipf_r2 = features.get('zipf_r_squared', 0.0)
    zipf_exp = features.get('zipf_exponent', 0.0)

    glossolalia = {
        'high_h2_h1_ratio': h2_h1 > 0.8,
        'low_ttr': ttr < 0.15,
        'very_low_h3': h3 < 0.5,
    }

    constructed = {
        'moderate_h2_h1_ratio': 0.4 <= h2_h1 <= 0.7,
        'zipfian': zipf_r2 > 0.9,
        'regular_exponent': 0.8 <= zipf_exp <= 1.2,
    }

    natural = {
        'natural_h2_h1_ratio': 0.3 <= h2_h1 <= 0.6,
        'zipfian': zipf_r2 > 0.85,
        'normal_ttr': 0.1 <= ttr <= 0.5,
    }

    encoded_natural = {
        'anomalous_h2_h1': h2_h1 < 0.3 or h2_h1 > 0.6,
        'zipfian': zipf_r2 > 0.85,
        'normal_ttr': 0.1 <= ttr <= 0.5,
    }

    # Score each type
    scores = {
        'glossolalia': sum(glossolalia.values()) / len(glossolalia),
        'constructed': sum(constructed.values()) / len(constructed),
        'natural': sum(natural.values()) / len(natural),
        'encoded_natural': sum(encoded_natural.values()) / len(encoded_natural),
    }

    best_type = max(scores, key=scores.get)
    confidence = scores[best_type]

    return TypologyClassification(
        voynich_features=features,
        glossolalia_indicators=glossolalia,
        constructed_lang_indicators=constructed,
        natural_lang_indicators=natural,
        encoded_natural_indicators=encoded_natural,
        most_likely_type=best_type,
        confidence=confidence,
    )


def _entropy_decay_rate(curve: Dict[int, float]) -> float:
    """Linear regression slope on entropy curve (order vs entropy)."""
    orders = sorted(curve.keys())
    if len(orders) < 2:
        return 0.0
    x = np.array(orders, dtype=float)
    y = np.array([curve[o] for o in orders], dtype=float)
    A = np.vstack([x, np.ones(len(x))]).T
    try:
        slope, _ = np.linalg.lstsq(A, y, rcond=None)[0]
    except np.linalg.LinAlgError:
        slope = 0.0
    return float(slope)


